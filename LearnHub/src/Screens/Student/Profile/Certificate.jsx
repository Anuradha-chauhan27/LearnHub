import "../../../assets/css/profile.css";
import jsPDF from "jspdf";
import { FaEye, FaDownload, FaShareAlt, FaAward, } from "react-icons/fa";
import { CustomButton } from "../../../Components/CustomButton"
const certificates = [
  {
    title: "React.js Bootcamp",
    date: "15 July 2026",
  },
  {
    title: "Node.js Fundamentals",
    date: "20 July 2026",
  },
  {
    title: "MongoDB Basics",
    date: "25 July 2026",
  },
];


export const Certificate = () => {
  const user = JSON.parse(localStorage.getItem("user"));

  const studentName = user?.name || "Student";

  const downloadCertificate = (course) => {

    const doc = new jsPDF("landscape");

    const today = new Date().toLocaleDateString("en-IN", {
      day: "2-digit",
      month: "long",
      year: "numeric",
    });

    // Outer Border
    doc.setDrawColor(30, 30, 30);
    doc.setLineWidth(1.5);
    doc.rect(10, 10, 277, 190);

    // Inner Border
    doc.setDrawColor(180, 180, 180);
    doc.setLineWidth(0.5);
    doc.rect(15, 15, 267, 180);

    // Heading
    doc.setTextColor(184, 134, 11);
    doc.setFontSize(28);
    doc.setFont("helvetica", "bold");
    doc.text("CERTIFICATE", 148, 35, {
      align: "center",
    });

    doc.setFontSize(18);
    doc.text("OF COMPLETION", 148, 48, {
      align: "center",
    });

    // Body
    doc.setTextColor(0, 0, 0);
    doc.setFont("times", "normal");
    doc.setFontSize(16);

    doc.text(
      "This certificate is proudly presented to",
      148,
      70,
      {
        align: "center",
      }
    );

    // Student Name
    doc.setFont("times", "bold");
    doc.setFontSize(26);

    doc.text(
      studentName.toUpperCase(),
      148,
      95,
      {
        align: "center",
      }
    );

    // Course
    doc.setFont("times", "normal");
    doc.setFontSize(16);

    doc.text(
      "For successfully completing the course",
      148,
      115,
      {
        align: "center",
      }
    );

    doc.setFont("times", "bold");
    doc.setFontSize(22);

    doc.text(
      course,
      148,
      130,
      {
        align: "center",
      }
    );

    // Date
    doc.setFont("helvetica", "normal");
    doc.setFontSize(14);

    doc.text(`Issued On: ${today}`, 30, 175);

    // Signature Line
    doc.line(205, 170, 260, 170);

    doc.setFontSize(14);
    doc.text("Instructor", 232, 178, {
      align: "center",
    });

    doc.setFont("helvetica", "bold");
    doc.text("LearnHub", 232, 186, {
      align: "center",
    });

    // Footer
    doc.setFontSize(12);
    doc.setTextColor(120);

    doc.text(
      "This certificate is digitally generated by LearnHub LMS.",
      148,
      194,
      {
        align: "center",
      }
    );

    doc.save(`${course}-Certificate.pdf`);
  };
  return (
    <div className="certificate-page">

      <div className="certificate-header">

        <h2>🎓 My Certificates</h2>

        <div className="certificate-count">
          <FaAward />
          <span>{certificates.length} Certificates</span>
        </div>

      </div>

      <div className="certificate-grid">

        {certificates.map((item, index) => (

          <div className="certificate-card" key={index}>

            <div className="certificate-preview">

              <FaAward className="certificate-icon" />

            </div>

            <div className="certificate-content">

              <h3>{item.title}</h3>

              <p>Issued: {item.date}</p>

              <div className="certificate-buttons">

                <CustomButton
                  onClick={() => downloadCertificate(item.title)}

                  text='View'
                />

                <CustomButton
                  onClick={() => downloadCertificate(item.title)}
                  text="Download"
                />

                <CustomButton
                  onClick={() => {
                    navigator.clipboard.writeText(
                      `I have successfully completed ${item.title} on LearnHub LMS 🎉`
                    );
                    alert("Certificate text copied to clipboard.");
                  }}

                  text="Share"
                />

              </div>

            </div>

          </div>

        ))}

      </div>

    </div>
  );
};